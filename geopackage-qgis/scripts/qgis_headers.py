#!/usr/bin/env python3
"""Assembles QGIS core's installed headers from a QGIS source checkout.

The native provider needs QGIS's C++ headers to build, and nothing else of
QGIS: on macOS and Linux it takes QGIS's symbols from the running QGIS when it
loads. Official QGIS application bundles ship without headers, so this script
makes the include directory a QGIS build would have installed, from the
source of the same release:

    git clone --depth 1 --branch final-4_0_2 https://github.com/qgis/QGIS qgis-4.0.2
    python3 scripts/qgis_headers.py qgis-4.0.2 build/qgis-4.0.2-include
    QGIS_INCLUDE_DIR=build/qgis-4.0.2-include ... cargo build --release

An installed include directory is QGIS's core headers, flattened, plus two
files CMake generates: ``qgis_core.h``, the export macros, and
``qgsconfig.h``, the version and build options. This writes both. Their
build options are those of a release build: ``QGISDEBUG`` stays undefined,
which matters, since it adds members to classes such as
``QgsCoordinateTransform``, and the optional features (``HAVE_AUTH`` and the
like) stay off, which changes nothing the provider uses.
"""

import argparse
import os
import re
import shutil
import sys

EXPORT_HEADER = """\
// Generated by geopackage-qgis/scripts/qgis_headers.py, as CMake's
// GenerateExportHeader writes it for a library that is used, not built.
#ifndef CORE_EXPORT_H
#define CORE_EXPORT_H

#ifdef CORE_STATIC_DEFINE
#  define CORE_EXPORT
#  define CORE_NO_EXPORT
#else
#  ifndef CORE_EXPORT
#    if defined(_MSC_VER)
#      define CORE_EXPORT __declspec(dllimport)
#    else
#      define CORE_EXPORT __attribute__((visibility("default")))
#    endif
#  endif
#  ifndef CORE_NO_EXPORT
#    if defined(_MSC_VER)
#      define CORE_NO_EXPORT
#    else
#      define CORE_NO_EXPORT __attribute__((visibility("hidden")))
#    endif
#  endif
#endif

#ifndef CORE_DEPRECATED
#  if defined(_MSC_VER)
#    define CORE_DEPRECATED __declspec(deprecated)
#  else
#    define CORE_DEPRECATED __attribute__ ((__deprecated__))
#  endif
#endif

#ifndef CORE_DEPRECATED_EXPORT
#  define CORE_DEPRECATED_EXPORT CORE_EXPORT CORE_DEPRECATED
#endif

#ifndef CORE_DEPRECATED_NO_EXPORT
#  define CORE_DEPRECATED_NO_EXPORT CORE_NO_EXPORT CORE_DEPRECATED
#endif

#endif /* CORE_EXPORT_H */
"""


def read_version(source):
    """``(major, minor, patch, release name)`` from the top-level
    CMakeLists.txt, or ``None`` if it isn't there."""
    path = os.path.join(source, "CMakeLists.txt")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        text = f.read()

    def field(name):
        match = re.search(rf'set\(\s*{name}\s+"?([^")\s]+)"?\s*\)', text)
        return match.group(1) if match else None

    major, minor, patch = (
        field(f"CPACK_PACKAGE_VERSION_{p}") for p in ("MAJOR", "MINOR", "PATCH")
    )
    if None in (major, minor, patch):
        return None
    name = re.search(r'set\(\s*RELEASE_NAME\s+"([^"]*)"\s*\)', text)
    return int(major), int(minor), int(patch), name.group(1) if name else ""


def render_config(template, major, minor, patch, release_name):
    """``qgsconfig.h`` from its template: the version filled in, every other
    variable empty, every ``#cmakedefine`` left undefined."""
    version_int = major * 10000 + minor * 100 + patch
    values = {
        "CPACK_PACKAGE_VERSION_MAJOR": str(major),
        "CPACK_PACKAGE_VERSION_MINOR": str(minor),
        "CPACK_PACKAGE_VERSION_PATCH": str(patch),
        "QGIS_VERSION_INT": str(version_int),
        "RELEASE_NAME": release_name,
    }
    lines = []
    for line in template.splitlines():
        define = re.match(r"\s*#cmakedefine\s+(\w+)", line)
        if define:
            lines.append(f"/* #undef {define.group(1)} */")
            continue
        lines.append(re.sub(r"\$\{(\w+)\}", lambda m: values.get(m.group(1), ""), line))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("source", help="a QGIS source checkout, at the release's tag")
    parser.add_argument("out", help="the include directory to write")
    parser.add_argument(
        "--version",
        help="MAJOR.MINOR.PATCH, if the checkout lacks its top-level CMakeLists.txt",
    )
    args = parser.parse_args()

    core = os.path.join(args.source, "src", "core")
    template = os.path.join(args.source, "cmake_templates", "qgsconfig.h.in")
    if not os.path.isdir(core) or not os.path.isfile(template):
        sys.exit(
            f"{args.source} is not a QGIS source checkout (no src/core, cmake_templates)"
        )
    # Header names are unique only within core; another library's could
    # shadow one of core's, so start from an empty directory.
    if os.path.isdir(args.out) and os.listdir(args.out):
        sys.exit(f"{args.out} is not empty")
    if args.version:
        major, minor, patch = (int(p) for p in args.version.split("."))
        release_name = ""
    else:
        found = read_version(args.source)
        if found is None:
            sys.exit("cannot read the version from CMakeLists.txt; pass --version")
        major, minor, patch, release_name = found
    if major < 4:
        sys.exit(
            f"the native provider builds against QGIS 4 or later, not {major}.{minor}"
        )

    os.makedirs(args.out, exist_ok=True)
    copied = {}
    for root, _dirs, files in os.walk(core):
        for name in files:
            if not name.endswith((".h", ".hpp")):
                continue
            if name in copied:
                # The installed directory is flat; QGIS keeps header names
                # unique for that reason.
                print(
                    f"warning: {name} in both {copied[name]} and {root}",
                    file=sys.stderr,
                )
                continue
            copied[name] = root
            shutil.copy2(os.path.join(root, name), os.path.join(args.out, name))
    # Core's headers include QGIS's vendored copy of nlohmann/json, which
    # QGIS installs beside them.
    nlohmann = os.path.join(args.source, "external", "nlohmann", "nlohmann")
    if not os.path.isdir(nlohmann):
        sys.exit(
            f"{args.source} has no external/nlohmann, which core's headers include"
        )
    shutil.copytree(nlohmann, os.path.join(args.out, "nlohmann"), dirs_exist_ok=True)
    with open(template, encoding="utf-8") as f:
        config = render_config(f.read(), major, minor, patch, release_name)
    with open(os.path.join(args.out, "qgsconfig.h"), "w", encoding="utf-8") as f:
        f.write(config)
    with open(os.path.join(args.out, "qgis_core.h"), "w", encoding="utf-8") as f:
        f.write(EXPORT_HEADER)
    print(f"QGIS {major}.{minor}.{patch}: {len(copied)} headers in {args.out}")


if __name__ == "__main__":
    main()
